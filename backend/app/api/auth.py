"""Google sign-in routes for the console.

The callback is on the API origin, so Google redirects the browser here and then
the server sends it back to the frontend with a short-lived code in the URL
fragment. The SPA trades that code for an opaque bearer token through
`/api/auth/exchange`. The Google client secret, the authorization code, and the
session token never meet in a URL the browser can share.

The routes are synchronous (`def`) because the account store uses a blocking
SQLAlchemy driver. FastAPI runs them in its threadpool, so the rest of the app
stays async.
"""

from __future__ import annotations

from typing import Literal

from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from fastapi.responses import RedirectResponse
from pydantic import BaseModel, Field

from app.accounts.models import UserRecord
from app.accounts.service import DEMO_NOTICE, AuthFlowError, AuthService
from app.auth import Principal
from app.config import Settings


class UserView(BaseModel):
    id: int
    subject: str
    email: str
    display_name: str | None = None
    provider: str


class ConfigView(BaseModel):
    enabled: bool
    provider: Literal["google"] = "google"
    login_url: str | None
    frontend_url: str
    session_ttl_seconds: int
    dev_login: bool
    # The names of the settings that are absent, never their values. A blank
    # client id is the most common reason the sign-in button stays greyed out,
    # and "enabled: false" on its own tells the operator nothing.
    missing: list[str] = []


class ExchangeRequest(BaseModel):
    # The code is generated by this server and is single-use. The cap is a guard
    # against a pasted access token or an accidental huge body.
    code: str = Field(min_length=1, max_length=256)


class ExchangeResponse(BaseModel):
    token: str
    token_type: Literal["bearer"] = "bearer"
    expires_at: int
    subject: str
    user: UserView
    demo_notice: str


class MeResponse(BaseModel):
    authenticated: bool
    auth_type: Literal["session", "token"]
    subject: str
    user: UserView | None = None
    session_expires_at: int | None = None
    demo_notice: str


class DisplayNameRequest(BaseModel):
    display_name: str = Field(min_length=1, max_length=80)


def _user_view(user: UserRecord) -> UserView:
    return UserView(
        id=user.id,
        subject=user.subject,
        email=user.email,
        display_name=user.display_name,
        provider=user.provider,
    )


def _principal_user(principal: Principal) -> UserView | None:
    if principal.auth_type != "session" or principal.user_id is None:
        return None
    return UserView(
        id=principal.user_id,
        subject=principal.subject,
        email=principal.email or "",
        display_name=principal.display_name,
        provider=principal.provider or "google",
    )


def _flow_error(exc: AuthFlowError) -> HTTPException:
    if exc.code == "auth_unavailable":
        code = status.HTTP_503_SERVICE_UNAVAILABLE
        follow_up = "Configure Google sign-in or use the development token."
    elif exc.code == "session_required":
        code = status.HTTP_403_FORBIDDEN
        follow_up = "Sign in with Google to change account settings."
    elif exc.code == "not_found":
        code = status.HTTP_404_NOT_FOUND
        follow_up = "This endpoint is only available in local development."
    else:
        code = status.HTTP_400_BAD_REQUEST
        follow_up = "Start the sign-in flow again."
    return HTTPException(
        status_code=code,
        detail={"code": exc.code.upper(), "message": exc.message, "follow_up": follow_up},
    )


def _no_store(response: Response) -> None:
    response.headers["Cache-Control"] = "no-store"


def _redirect(url: str) -> RedirectResponse:
    return RedirectResponse(url=url, status_code=status.HTTP_302_FOUND, headers={"Cache-Control": "no-store"})


def build_auth_router(settings: Settings, service: AuthService, require_principal) -> APIRouter:
    api = APIRouter(prefix="/api/auth", tags=["auth"])

    @api.get("/config", response_model=ConfigView)
    def config(response: Response) -> ConfigView:
        _no_store(response)
        missing = []
        if not settings.google_client_id:
            missing.append("ALEXA_GOOGLE_CLIENT_ID")
        if not settings.google_client_secret:
            missing.append("ALEXA_GOOGLE_CLIENT_SECRET")
        return ConfigView(
            enabled=service.google_enabled,
            login_url="/api/auth/google/start" if service.google_enabled else None,
            frontend_url=settings.frontend_origin,
            session_ttl_seconds=settings.session_ttl_seconds,
            dev_login=service.dev_login_enabled,
            missing=missing,
        )

    # Two spellings are kept on purpose: `/google/start` is the name the console
    # uses, and `/login/google` is the simpler form used in the deployment docs.
    @api.get("/google/start")
    @api.get("/login/google")
    def start(
        redirect_after: str | None = Query(default=None, max_length=300),
        next: str | None = Query(default=None, max_length=300),
    ) -> RedirectResponse:
        try:
            return _redirect(service.start(redirect_after or next))
        except AuthFlowError as exc:
            raise _flow_error(exc) from exc

    @api.get("/callback/google")
    def callback(
        state: str | None = Query(default=None, max_length=128),
        code: str | None = Query(default=None, max_length=4096),
        error: str | None = Query(default=None, max_length=64),
    ) -> RedirectResponse:
        try:
            result = service.complete(state=state, code=code, error=error)
        except AuthFlowError as exc:
            # The browser is navigating, so an error is a redirect with a stable
            # code, not a JSON body it would render as a blank page.
            return _redirect(service.login_url(error=exc.code))
        return _redirect(service.login_url(code=result.code, next_path=result.redirect_after))

    @api.post("/exchange", response_model=ExchangeResponse)
    def exchange(payload: ExchangeRequest, response: Response) -> ExchangeResponse:
        _no_store(response)
        try:
            result = service.exchange(payload.code)
        except AuthFlowError as exc:
            raise _flow_error(exc) from exc
        return ExchangeResponse(
            token=result.token,
            expires_at=int(result.expires_at.timestamp()),
            subject=result.user.subject,
            user=_user_view(result.user),
            demo_notice=DEMO_NOTICE,
        )

    @api.get("/me", response_model=MeResponse)
    def me(
        response: Response,
        principal: Principal = Depends(require_principal),
    ) -> MeResponse:
        _no_store(response)
        return MeResponse(
            authenticated=True,
            auth_type=principal.auth_type,
            subject=principal.subject,
            user=_principal_user(principal),
            session_expires_at=(
                int(principal.session_expires_at.timestamp()) if principal.session_expires_at else None
            ),
            demo_notice=DEMO_NOTICE,
        )

    @api.patch("/me", response_model=UserView)
    def update_me(
        payload: DisplayNameRequest,
        response: Response,
        principal: Principal = Depends(require_principal),
    ) -> UserView:
        _no_store(response)
        try:
            user = service.update_display_name(principal, payload.display_name)
        except AuthFlowError as exc:
            raise _flow_error(exc) from exc
        return _user_view(user)

    @api.post("/logout", status_code=status.HTTP_204_NO_CONTENT)
    def logout(principal: Principal = Depends(require_principal)) -> Response:
        service.logout(principal)
        # A new Response replaces the injected one, so set the header here
        # rather than on a response object that is discarded.
        return Response(
            status_code=status.HTTP_204_NO_CONTENT,
            headers={"Cache-Control": "no-store"},
        )

    @api.post("/dev-login", response_model=ExchangeResponse)
    def dev_login(response: Response) -> ExchangeResponse:
        # The service only enables this on a local origin. A deployed instance
        # returns 404 even if the environment is misconfigured.
        _no_store(response)
        try:
            result = service.dev_login()
        except AuthFlowError as exc:
            raise _flow_error(exc) from exc
        return ExchangeResponse(
            token=result.token,
            expires_at=int(result.expires_at.timestamp()),
            subject=result.user.subject,
            user=_user_view(result.user),
            demo_notice=DEMO_NOTICE,
        )

    return api


__all__ = [
    "ConfigView",
    "DisplayNameRequest",
    "ExchangeRequest",
    "ExchangeResponse",
    "MeResponse",
    "UserView",
    "build_auth_router",
]
